import assert from "node:assert/strict";
import test from "node:test";
import { loginAction, sessionState, signOut } from "../apps/web/components/auth/login-action";
const user = { id: "synthetic", emailVerified: true, twoFactorEnabled: true };
const session = { userId: "synthetic", mfaVerifiedAt: new Date().toISOString() };

test("session routing requires matching verified identity and authoritative MFA stamp", () => {
  assert.equal(sessionState(null), "absent");
  assert.equal(sessionState({ user, session: { ...session, userId: "foreign" } }), "absent");
  assert.equal(sessionState({ user: { ...user, emailVerified: false }, session }), "unverified");
  assert.equal(sessionState({ user, session: { ...session, mfaVerifiedAt: null } }), "challenge");
  assert.equal(sessionState({ user, session: { ...session, mfaVerifiedAt: "invalid" } }), "challenge");
  assert.equal(sessionState({ user, session }), "ready");
  assert.equal(sessionState({ user: { ...user, twoFactorEnabled: false }, session: { userId: user.id } }), "ready");
});
test("login follows challenge without granting access, then confirms the real session", async t => {
  let values: Response[] = [];
  const calls: { path: string; init?: RequestInit }[] = [];
  t.mock.method(globalThis, "fetch", async (path: string | URL | Request, init?: RequestInit) => { calls.push({ path: String(path), init }); const value = values.shift(); assert.ok(value); return value; });
  const json = (value: unknown, status = 200, headers = {}) => new Response(JSON.stringify(value), { status, headers });
  const signal = new AbortController().signal;
  const credentials = { operation: "sign-in", email: "synthetic@example.test", password: "Synthetic-password-42" } as const;
  values = [json({ twoFactorRedirect: true })];
  assert.deepEqual(await loginAction(credentials, signal), { status: "success", next: "two-factor" });
  assert.equal(calls.length, 1);
  assert.equal(calls[0]?.init?.credentials, "same-origin");
  values = [json({ token: "must-not-be-stored" }), json(null)];
  assert.equal((await loginAction(credentials, signal)).status, "error");
  values = [json({ token: "not-authority" }), json({ user, session })];
  assert.deepEqual(await loginAction({ operation: "verify-totp", code: "123456" }, signal), { status: "success", next: "auth-complete" });
  assert.deepEqual(JSON.parse(String(calls.at(-2)?.init?.body)), { code: "123456", trustDevice: false });
  values = [json({ code: "EMAIL_NOT_VERIFIED", message: "private" }, 403)];
  const unverified = await loginAction(credentials, signal);
  assert.equal(unverified.status === "error" && unverified.code, "email_unverified");
  values = [json({ code: "INVALID_TWO_FACTOR_COOKIE" }, 401)];
  const expired = await loginAction({ operation: "verify-backup-code", code: "synthetic" }, signal);
  assert.equal(expired.status === "error" && expired.code, "challenge_expired");
  values = [json({ message: "private" }, 429, { "X-Retry-After": "13" })];
  const limited = await loginAction(credentials, signal);
  assert.equal(limited.status === "error" && limited.retryAfterSeconds, 13);
  values = [json({ error: { code: "internal_error", message: "private" } }, 500)];
  assert.ok(!JSON.stringify(await loginAction(credentials, signal)).includes("private"));
  values = [json({ success: true }), json({ user, session })];
  assert.equal((await signOut(signal)).status, "error");
  values = [json({ success: true }), json(null)];
  assert.equal((await signOut(signal)).status, "success");
  const before = calls.length;
  assert.equal((await loginAction({ operation: "enable-totp", password: "not-connected" }, signal)).status, "error");
  assert.equal(calls.length, before);
});
