import assert from "node:assert/strict";
import test from "node:test";
import { parseEnrollment, startEnrollment, enrollmentSession } from "../apps/web/components/auth/enrollment-action";
const email = "synthetic@example.test";
const sample = { method: "totp", totpURI: "otpauth://totp/RenewRelay:synthetic%40example.test?secret=JBSWY3DPEHPK3PXP&issuer=RenewRelay", backupCodes: ["SYNTHETIC-12345", "SYNTHETIC-67890"] };
test("enrollment parser binds the provisioning URI to expected issuer/address and valid material", () => {
  assert.equal(parseEnrollment(sample, email)?.setupKey, "JBSWY3DPEHPK3PXP");
  assert.equal(parseEnrollment(sample, "foreign@example.test"), null);
  assert.equal(parseEnrollment({ ...sample, totpURI: sample.totpURI.replace("otpauth:", "https:") }, email), null);
  assert.equal(parseEnrollment({ ...sample, backupCodes: ["SYNTHETIC-12345", "SYNTHETIC-12345"] }, email), null);
  assert.equal(parseEnrollment({ ...sample, totpURI: sample.totpURI + "&digits=8" }, email), null);
  assert.equal(parseEnrollment({ ...sample, method: "otp" }, email), null);
});
test("enrollment adapter sends password confirmation to existing endpoint and requires authoritative activation", async t => {
  let next: Response;
  const calls: { path: string; init?: RequestInit }[] = [];
  t.mock.method(globalThis, "fetch", async (path: string | URL | Request, init?: RequestInit) => { calls.push({ path: String(path), init }); return next; });
  const signal = new AbortController().signal;
  next = new Response(JSON.stringify(sample));
  const started = await startEnrollment("Synthetic-passphrase-42", email, signal);
  assert.equal(started.result.status, "success");
  assert.ok(started.material);
  assert.equal(calls[0]?.path, "/api/auth/two-factor/enable");
  assert.equal(calls[0]?.init?.credentials, "same-origin");
  assert.deepEqual(JSON.parse(String(calls[0]?.init?.body)), { password: "Synthetic-passphrase-42", method: "totp" });
  next = new Response(JSON.stringify({ code: "INVALID_PASSWORD", message: "private internal message" }), { status: 400 });
  const invalid = await startEnrollment("bad", email, signal);
  assert.equal(invalid.result.status, "error"); assert.ok(!JSON.stringify(invalid).includes("private"));
  next = new Response(JSON.stringify({ error: { code: "reauthentication_required" } }), { status: 403 });
  const stale = await startEnrollment("bad", email, signal);
  assert.equal(stale.result.status === "error" && stale.result.code, "reauthentication_required");
  next = new Response(JSON.stringify({ user: { id: "synthetic", emailVerified: true, twoFactorEnabled: false }, session: { userId: "synthetic" } }));
  assert.equal((await enrollmentSession("synthetic", signal)).status, "success");
  next = new Response(JSON.stringify({ user: { id: "synthetic", emailVerified: true, twoFactorEnabled: false }, session: { userId: "synthetic" } }));
  assert.equal((await enrollmentSession("synthetic", signal, true)).status, "error");
  next = new Response(JSON.stringify({ user: { id: "other", emailVerified: true, twoFactorEnabled: true }, session: { userId: "other", mfaVerifiedAt: new Date().toISOString() } }));
  assert.equal((await enrollmentSession("synthetic", signal, true)).status, "error");
  next = new Response(JSON.stringify({ user: { id: "synthetic", emailVerified: true, twoFactorEnabled: true }, session: { userId: "synthetic", mfaVerifiedAt: new Date().toISOString() } }));
  assert.equal((await enrollmentSession("synthetic", signal, true)).status, "success");
});
